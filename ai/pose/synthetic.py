"""Offline synthetic scene generator.

Purpose
-------
FallGuard AI must be demonstrable with **no camera and no external dataset**. This module
renders a short video of a *fictional* stick figure that stands, moves, then collapses to
the floor. The result is written to ``data/samples/`` and is fed through the **real**
MediaPipe Pose estimator, so the whole pipeline runs for real:

    synthetic video -> MediaPipe -> 33 landmarks -> preprocessing -> LSTM -> event

What this is **not**
-------------------
* It is not a fall-detection dataset. A rendered figure is not a human.
* Nothing trained or evaluated on it is a benchmark. Every artefact derived from it is
  labelled ``SYNTHETIC`` in its filename, in its metadata and on the console.
* Its only purposes are (a) exercising the software pipeline end to end, (b) giving the
  dashboard something privacy-safe to draw, and (c) providing a smoke-test fixture.

For real evaluation, use a genuine fall dataset -- see ``docs/model.md``.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path
from typing import Final, Sequence

import numpy as np

from ai.logging_config import get_logger
from ai.pose.landmarks import (
    LEFT_ANKLE,
    LEFT_ELBOW,
    LEFT_HIP,
    LEFT_KNEE,
    LEFT_SHOULDER,
    LEFT_WRIST,
    NOSE,
    RIGHT_ANKLE,
    RIGHT_ELBOW,
    RIGHT_HIP,
    RIGHT_KNEE,
    RIGHT_SHOULDER,
    RIGHT_WRIST,
)

logger = get_logger(__name__)

SYNTHETIC_BANNER: Final[str] = (
    "SYNTHETIC DATA -- generated by ai/pose/synthetic.py. "
    "Rendered fictional figure, not real footage. Not a benchmark dataset."
)

FRAME_WIDTH: Final[int] = 640
FRAME_HEIGHT: Final[int] = 480
#: y coordinate (normalised) of the floor line.
FLOOR_Y: Final[float] = 0.83

# Landmark index -> (x, y) for the two reference poses, in normalised image coordinates.
_UPRIGHT: Final[dict[int, tuple[float, float]]] = {
    NOSE: (0.500, 0.130),
    LEFT_SHOULDER: (0.440, 0.270),
    RIGHT_SHOULDER: (0.560, 0.270),
    LEFT_ELBOW: (0.420, 0.410),
    RIGHT_ELBOW: (0.580, 0.410),
    LEFT_WRIST: (0.410, 0.550),
    RIGHT_WRIST: (0.590, 0.550),
    LEFT_HIP: (0.465, 0.545),
    RIGHT_HIP: (0.535, 0.545),
    LEFT_KNEE: (0.470, 0.710),
    RIGHT_KNEE: (0.530, 0.710),
    LEFT_ANKLE: (0.475, 0.875),
    RIGHT_ANKLE: (0.525, 0.875),
}

#: Person lying on their back, head to the left, limbs splayed. Hip is close to the floor
#: and the torso axis is horizontal -- the two cues a fall produces.
_ON_FLOOR: Final[dict[int, tuple[float, float]]] = {
    NOSE: (0.150, 0.770),
    LEFT_SHOULDER: (0.265, 0.795),
    RIGHT_SHOULDER: (0.305, 0.860),
    LEFT_ELBOW: (0.360, 0.690),
    RIGHT_ELBOW: (0.400, 0.955),
    LEFT_WRIST: (0.460, 0.640),
    RIGHT_WRIST: (0.505, 0.985),
    LEFT_HIP: (0.500, 0.845),
    RIGHT_HIP: (0.545, 0.885),
    LEFT_KNEE: (0.680, 0.855),
    RIGHT_KNEE: (0.700, 0.960),
    LEFT_ANKLE: (0.850, 0.855),
    RIGHT_ANKLE: (0.870, 1.010),
}

#: The joints the renderer actually draws. Everything else is left undefined, which
#: keeps the figure readable instead of a cloud of 33 dots.
_DRAWN_LANDMARKS: Final[tuple[int, ...]] = tuple(_UPRIGHT)


@dataclass(frozen=True, slots=True)
class SceneScript:
    """Timeline of the synthetic clip, in frames.

    ``segments`` is a list of ``(label, frame_count)``. The fall is placed late enough
    that the sequence buffer has already filled with normal-activity windows.
    """

    segments: tuple[tuple[str, int], ...] = (
        ("idle", 45),
        ("walk", 45),
        ("idle", 30),
        ("fall", 30),
        ("on_floor", 45),
    )

    @property
    def total_frames(self) -> int:
        return sum(count for _, count in self.segments)

    def fall_frame_range(self) -> tuple[int, int]:
        start = 0
        for label, count in self.segments:
            if label == "fall":
                return start, start + count
            start += count
        return 0, 0

    def ground_truth(self) -> np.ndarray:
        """Per-frame label: 1 while the figure is falling or already down, else 0."""
        labels = np.zeros(self.total_frames, dtype=np.int64)
        start, end = self.fall_frame_range()
        if end > start:
            labels[start:] = 1
        return labels


def _smoothstep(t: float) -> float:
    t = float(np.clip(t, 0.0, 1.0))
    return t * t * (3.0 - 2.0 * t)


def landmarks_for_frame(script: SceneScript, frame_index: int) -> np.ndarray:
    """Ground-truth-ish landmark array ``(33, 2)`` in normalised coordinates for a frame.

    Not a MediaPipe output -- this is the *input* to the renderer. Use
    :class:`~ai.pose.pose_estimator.PoseEstimator` on the rendered frame to obtain real
    detections.
    """
    pose = {index: np.array(point, dtype=np.float64) for index, point in _UPRIGHT.items()}
    sway = 0.0
    stride = 0.0

    frame_index = int(np.clip(frame_index, 0, script.total_frames - 1))
    offset = 0
    for label, count in script.segments:
        if frame_index < offset + count:
            progress = (frame_index - offset) / max(count - 1, 1)
            if label == "walk":
                sway = 0.30 * math.sin(2.0 * math.pi * progress)
                stride = 0.35 * math.sin(4.0 * math.pi * progress)
            elif label == "fall":
                ease = _smoothstep(progress)
                for index in _UPRIGHT:
                    start = _UPRIGHT[index]
                    end = _ON_FLOOR[index]
                    pose[index] = np.array(
                        [start[0] + (end[0] - start[0]) * ease,
                         start[1] + (end[1] - start[1]) * ease],
                        dtype=np.float64,
                    )
                return _to_array(pose)
            break
        offset += count

    for index, point in pose.items():
        # Limbs swing; the torso and head stay comparatively stable.
        if index in (LEFT_WRIST, RIGHT_WRIST, LEFT_ELBOW, RIGHT_ELBOW):
            pose[index] = point + np.array([sway * 0.06, stride * 0.02])
        elif index in (LEFT_KNEE, RIGHT_KNEE):
            pose[index] = point + np.array([stride * 0.02, 0.0])
        elif index in (LEFT_ANKLE, RIGHT_ANKLE):
            pose[index] = point + np.array([stride * 0.03, abs(stride) * 0.01])
        elif index == NOSE:
            pose[index] = point + np.array([sway * 0.01, 0.0])
    return _to_array(pose)


def _to_array(pose: dict[int, np.ndarray]) -> np.ndarray:
    array = np.zeros((33, 2), dtype=np.float64)
    for index, point in pose.items():
        array[index] = point
    return array


# --------------------------------------------------------------------------- #
# Rendering
# --------------------------------------------------------------------------- #
# Palette and shading were chosen empirically: MediaPipe's pose detector is trained on
# photographs, and these values are the ones it reliably locks onto for this figure. Do
# not change them casually -- re-measure the detection rate with
# ``scripts/generate_sample_data.py --check-detection`` after any change.
_BACKGROUND_TOP = np.array([90, 95, 105], dtype=np.float32)
_BACKGROUND_BOTTOM = np.array([120, 125, 135], dtype=np.float32)
_FLOOR_COLOR = (70, 75, 85)
_FLOOR_LINE = (78, 83, 93)
_SHIRT = (70, 110, 190)
_TROUSERS = (60, 70, 110)
_SKIN = (150, 180, 215)
_SHOE = (40, 40, 45)
_OUTLINE = (52, 58, 72)


def _background(width: int, height: int) -> np.ndarray:
    ramp = np.linspace(0.0, 1.0, height, dtype=np.float32)[:, None]
    column = _BACKGROUND_TOP[None, :] * (1.0 - ramp) + _BACKGROUND_BOTTOM[None, :] * ramp
    image = np.repeat(column[:, None, :], width, axis=1).astype(np.uint8)
    floor_y = int(FLOOR_Y * height)
    image[floor_y:, :] = _FLOOR_COLOR
    for x in range(0, width, 60):
        cv2_line(image, (x, floor_y), (x, height), _FLOOR_LINE, 1)
    return image


def cv2_line(image: np.ndarray, start: tuple[int, int], end: tuple[int, int],
             color: tuple[int, int, int], thickness: int) -> None:
    """``cv2.line`` wrapper that tolerates the absence of OpenCV at import time."""
    import cv2

    cv2.line(image, start, end, color, thickness, cv2.LINE_AA)


def _tapered_limb(
    image: np.ndarray,
    start: tuple[float, float],
    end: tuple[float, float],
    width_start: float,
    width_end: float,
    color: tuple[int, int, int],
) -> None:
    """Draw a limb as a convex quad so joints do not bowtie into an hourglass."""
    import cv2

    start_point = np.array(start, dtype=np.float64)
    end_point = np.array(end, dtype=np.float64)
    direction = end_point - start_point
    length = float(np.linalg.norm(direction))
    if length < 1e-3:
        return
    normal = np.array([-direction[1], direction[0]]) / length
    quad = np.array([
        start_point + normal * width_start,
        end_point + normal * width_end,
        end_point - normal * width_end,
        start_point - normal * width_start,
    ])
    cv2.fillPoly(image, [quad.astype(np.int32)], color)


def render_frame(landmarks_2d: np.ndarray, width: int = FRAME_WIDTH,
                 height: int = FRAME_HEIGHT) -> np.ndarray:
    """Draw one BGR frame from a ``(33, 2)`` normalised landmark array."""
    import cv2

    image = _background(width, height)

    def point(index: int) -> tuple[float, float]:
        return (float(landmarks_2d[index, 0]) * width, float(landmarks_2d[index, 1]) * height)

    # Far-side limbs first, then torso, then near-side limbs, so the figure reads as 3-D.
    for shoulder, elbow, wrist in (
        (LEFT_SHOULDER, LEFT_ELBOW, LEFT_WRIST),
        (RIGHT_SHOULDER, RIGHT_ELBOW, RIGHT_WRIST),
    ):
        _tapered_limb(image, point(shoulder), point(elbow), 20, 15, _SHIRT)
        _tapered_limb(image, point(elbow), point(wrist), 15, 11, _SKIN)
        cv2.circle(image, (int(point(wrist)[0]), int(point(wrist)[1])), 13, _SKIN, -1, cv2.LINE_AA)

    _tapered_limb(image, point(LEFT_SHOULDER), point(LEFT_HIP), 34, 30, _SHIRT)
    _tapered_limb(image, point(RIGHT_SHOULDER), point(RIGHT_HIP), 34, 30, _SHIRT)
    _tapered_limb(image, point(LEFT_HIP), point(RIGHT_HIP), 32, 32, _SHIRT)

    # Neck and head. The neck deliberately runs to the *left* hip with a constant width:
    # routing it to the hip midpoint with a flaring width merges it into the shirt, and
    # MediaPipe then fails to find the torso at all.
    head = point(NOSE)
    _tapered_limb(image, (head[0], head[1] + 18), point(LEFT_HIP), 16, 16, _SKIN)
    cv2.ellipse(
        image, (int(head[0]), int(head[1])), (30, 36), 0, 0, 360, _SKIN, -1, cv2.LINE_AA
    )
    cv2.ellipse(
        image, (int(head[0]), int(head[1])), (30, 36), 0, 0, 360, _OUTLINE, 2, cv2.LINE_AA
    )
    cv2.ellipse(
        image, (int(head[0]), int(head[1] - 12)), (30, 26), 0, 180, 360, (44, 48, 62), -1,
        cv2.LINE_AA,
    )
    for offset in (-11, 11):
        cv2.circle(
            image, (int(head[0] + offset), int(head[1] - 2)), 3, (32, 32, 42), -1, cv2.LINE_AA
        )
    cv2.ellipse(
        image, (int(head[0]), int(head[1] + 15)), (9, 5), 0, 0, 360, (118, 138, 176), -1,
        cv2.LINE_AA,
    )

    for hip, knee, ankle in (
        (LEFT_HIP, LEFT_KNEE, LEFT_ANKLE),
        (RIGHT_HIP, RIGHT_KNEE, RIGHT_ANKLE),
    ):
        _tapered_limb(image, point(hip), point(knee), 24, 20, _TROUSERS)
        _tapered_limb(image, point(knee), point(ankle), 20, 15, _TROUSERS)
        foot = point(ankle)
        cv2.ellipse(
            image, (int(foot[0]), int(foot[1])), (18, 9), 0, 0, 360, _SHOE, -1, cv2.LINE_AA
        )

    return image


#: Video writers tried in order. ``FFV1`` is lossless and matters: with the lossy
#: ``mp4v`` codec, compression artefacts on the limbs cost ~55% of MediaPipe's detections
#: on this figure (measured -- see ``scripts/generate_sample_data.py --check-detection``).
VIDEO_WRITERS: Final[tuple[tuple[str, str], ...]] = (("FFV1", ".avi"), ("mp4v", ".mp4"))


def _open_writer(destination: Path, fps: int, size: tuple[int, int]):
    """Open a lossless writer, falling back to the platform's lossy encoder.

    Returns ``(writer, path_actually_written)``; the path can differ from
    ``destination`` because the chosen container determines the extension.
    """
    import cv2

    for codec, extension in VIDEO_WRITERS:
        target = destination.with_suffix(extension)
        fourcc = cv2.VideoWriter_fourcc(*codec)
        try:
            writer = cv2.VideoWriter(str(target), fourcc, float(fps), size)
        except Exception:
            logger.debug("VideoWriter raised for codec %s", codec, exc_info=True)
            continue
        if writer.isOpened():
            return writer, target
        try:
            writer.release()
        except Exception:  # pragma: no cover - defensive
            logger.debug("Failed to release a rejected VideoWriter", exc_info=True)
        logger.debug("VideoWriter rejected codec %s for %s", codec, target.name)
    raise RuntimeError(
        f"OpenCV could not open a VideoWriter for '{destination}' with any known codec "
        f"({', '.join(codec for codec, _ in VIDEO_WRITERS)})"
    )


def _draw_watermark(image: np.ndarray, frame_index: int, total_frames: int) -> None:
    """Burn a ``SYNTHETIC`` mark into the bottom-left corner.

    Deliberately *no* filled banner across the top of the frame: a full-width dark band
    creates a strong horizontal edge that suppresses MediaPipe's detector (measured: the
    detection rate on this figure fell from 99% to 53% with a top banner). A small
    outlined caption in the corner is legible and inert.
    """
    import cv2

    label = f"SYNTHETIC {frame_index:04d}/{total_frames}"
    height, width = image.shape[:2]
    origin = (10, height - 12)
    cv2.putText(
        image, label, origin, cv2.FONT_HERSHEY_SIMPLEX, 0.45, (45, 45, 52), 3, cv2.LINE_AA
    )
    cv2.putText(
        image, label, origin, cv2.FONT_HERSHEY_SIMPLEX, 0.45, (205, 215, 228), 1, cv2.LINE_AA
    )
    del width


def generate_sample_video(
    output_path: str | Path,
    *,
    fps: int = 30,
    width: int = FRAME_WIDTH,
    height: int = FRAME_HEIGHT,
    script: SceneScript | None = None,
    overlay_label: bool = True,
) -> Path:
    """Render the synthetic clip to ``output_path`` and return the path actually written.

    A ``SYNTHETIC`` watermark is burned into the corner of every frame so an exported
    still can never be mistaken for surveillance footage.
    """
    import cv2

    script = script or SceneScript()
    destination = Path(output_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    writer, target = _open_writer(destination, fps, (width, height))

    try:
        for index in range(script.total_frames):
            landmarks = landmarks_for_frame(script, index)
            image = render_frame(landmarks, width, height)
            if overlay_label:
                _draw_watermark(image, index, script.total_frames)
            writer.write(image)
    finally:
        writer.release()

    logger.info(
        "Generated %s (%d synthetic frames at %d fps) -- %s",
        target.name, script.total_frames, fps, SYNTHETIC_BANNER,
    )
    return target


def draw_skeleton(
    image: np.ndarray,
    landmarks: np.ndarray,
    connections: Sequence[tuple[int, int]],
    *,
    color: tuple[int, int, int] = (96, 224, 160),
    thickness: int = 2,
) -> np.ndarray:
    """Overlay a pose skeleton on a copy of ``image``.

    The dashboard and the demo use this so a human viewer sees a *skeleton* rather than
    raw footage, which is the default privacy-preserving visualisation.
    """
    import cv2

    output = image.copy()
    height, width = output.shape[:2]
    for start_index, end_index in connections:
        start = landmarks[start_index]
        end = landmarks[end_index]
        if start[3] < 0.3 or end[3] < 0.3:
            continue
        cv2.line(
            output,
            (int(start[0] * width), int(start[1] * height)),
            (int(end[0] * width), int(end[1] * height)),
            color, thickness, cv2.LINE_AA,
        )
    return output
